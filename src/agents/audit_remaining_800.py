FOUR_PERSPECTIVE_PROMPT = """Audit one software issue in four clearly separated stages within this single response.
All four outputs are generated by the same model call; they are perspectives, not independent agents.

Policy perspective: classify observed malfunction versus feature/request.
Data perspective: use metadata and graph evidence; missing fields are normal, metadata alone is not proof.
Pattern perspective: identify concrete bug symptoms versus enhancement language.
Judge perspective: review the three perspectives and their evidence; resolve conflicts and choose a final label.
Use the original label only as context for the Judge, never as ground truth.

Return only valid JSON matching this shape:
{"policy":{"label":"bug|non-bug","confidence":0.0,"reason":"<=10 words","evidence":["short fact"]},
"data":{"label":"bug|non-bug","confidence":0.0,"reason":"<=10 words","evidence":["short fact"]},
"pattern":{"label":"bug|non-bug","confidence":0.0,"reason":"<=10 words","evidence":["short fact"]},
"judge":{"final_label":"bug|non-bug","reasoning_summary":"<=20 words","evidence":["short decisive fact"]}}
Use numeric confidence from 0.0 to 1.0 for the three perspectives. Include at most one short evidence phrase per perspective and for the Judge. Do not include Judge confidence."""


class FourPerspectiveAgent(BaseAuditAgent):
    """Returns the three auditor perspectives and Judge decision in one model call."""

    def __init__(self, model: str = "openrouter/free", provider: str = "openrouter", **kwargs):
        if provider == "openrouter":
            kwargs.setdefault("max_completion_tokens", 1000)
        elif "openai" in model or "120b" in model or "20b" in model or "free" in model:
            kwargs.setdefault("max_completion_tokens", 750)
        else:
            kwargs.setdefault("max_completion_tokens", 512)
        kwargs.setdefault("min_request_interval_seconds", 0.5)
        super().__init__(name="four_perspective_audit", model=model, provider=provider, **kwargs)

    async def evaluate_issue(self, issue: dict[str, Any]) -> AuditedIssueRecord:
        kg_evidence = get_kg_retriever().retrieve_evidence_for_issue(issue)
        user_prompt = f"""Project: {issue.get('project', '')}; source: {issue.get('source', '')}
Issue title: {issue.get('title', '')}
Issue text: {str(issue.get('model_text') or issue.get('description') or '')[:700]}
Metadata: component={issue.get('component')}; severity={issue.get('severity')}; priority={issue.get('priority')}; status={issue.get('status')}; resolution={issue.get('resolution')}
Knowledge graph evidence: {'; '.join(kg_evidence[:3]) or 'none available'}
Original source label for Judge context only: {issue.get('original_label', '')}
Produce the three perspective decisions, then the Judge decision in the required JSON format."""

        usage_before = (self.prompt_tokens, self.completion_tokens)
        result = await self._generate_json_response(FOUR_PERSPECTIVE_PROMPT, user_prompt)
        prompt_used = self.prompt_tokens - usage_before[0]
        comp_used = self.completion_tokens - usage_before[1]

        verdicts: list[AgentVerdict] = []
        for perspective, agent_name in (("policy", "policy_agent"), ("data", "data_agent"), ("pattern", "pattern_agent")):
            raw = result.get(perspective, {})
            label = str(raw.get("label", "")).lower().strip()
            if "non" in label:
                label = "non-bug"
            elif "bug" in label:
                label = "bug"
            else:
                label = "bug"
            try:
                confidence = float(raw.get("confidence", 0.8))
            except Exception:
                confidence = 0.8
            confidence = max(0.0, min(1.0, confidence))
            verdicts.append(AgentVerdict(
                agent=agent_name,
                label=label,
                confidence=confidence,
                reason=str(raw.get("reason", ""))[:300],
                evidence=[str(item)[:200] for item in raw.get("evidence", [])][:2],
            ))

        judge_raw = result.get("judge", {})
        final_label = str(judge_raw.get("final_label", "")).lower().strip()
        if "non" in final_label:
            final_label = "non-bug"
        elif "bug" in final_label:
            final_label = "bug"
        else:
            final_label = "bug"

        labels = [v.label for v in verdicts]
        majority = max(labels.count("bug"), labels.count("non-bug"))
        agreement = round(majority / len(labels), 2)
        supporters = [v.confidence for v in verdicts if v.label == final_label]
        confidence = round(sum(supporters) / len(supporters) * agreement, 2) if supporters else 0.8

        orig_label = str(issue.get("original_label", "")).lower().strip()
        norm_orig = "non-bug" if "non" in orig_label else "bug"
        label_flipped = (final_label != norm_orig)

        policy_v, data_v, pattern_v = verdicts[0], verdicts[1], verdicts[2]

        return AuditedIssueRecord(
            source=str(issue.get("source", "")),
            project=str(issue.get("project", "")),
            issue_id=str(issue.get("issue_id", "")),
            original_label=norm_orig,
            policy_label=policy_v.label,
            policy_confidence=policy_v.confidence,
            policy_reason=policy_v.reason,
            policy_evidence=policy_v.evidence,
            data_label=data_v.label,
            data_confidence=data_v.confidence,
            data_reason=data_v.reason,
            data_evidence=data_v.evidence,
            pattern_label=pattern_v.label,
            pattern_confidence=pattern_v.confidence,
            pattern_reason=pattern_v.reason,
            pattern_evidence=pattern_v.evidence,
            judge_label=final_label,
            judge_confidence=confidence,
            judge_reasoning=str(judge_raw.get("reasoning_summary", ""))[:500],
            judge_evidence=[str(item)[:200] for item in judge_raw.get("evidence", [])][:2],
            agent_agreement=agreement,
            label_flipped=label_flipped,
            audit_timestamp=datetime.now(timezone.utc).isoformat(),
            audit_method="single_model_four_perspective_one_call",
            audit_provider=self.provider,
            audit_model=self.model,
            api_prompt_tokens=prompt_used,
            api_completion_tokens=comp_used,
        )


def save_checkpoint(records: list[dict[str, Any]], json_path: Path, parquet_path: Path) -> None:
    json_path.parent.mkdir(parents=True, exist_ok=True)
    parquet_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_json = json_path.with_suffix(".json.tmp")
    tmp_parquet = parquet_path.with_suffix(parquet_path.suffix + ".tmp")
    tmp_json.write_text(json.dumps(records, indent=2), encoding="utf-8")
    df = pd.DataFrame(records)
    df.to_parquet(tmp_parquet, index=False)
    tmp_json.replace(json_path)
    tmp_parquet.replace(parquet_path)
    print(f"[Checkpoint] Saved {len(records)} audited records to {json_path}")


async def run_audit(
    sample_parquet: Path = Path("data/processed/audit_train_sample_1000_from_5000.parquet"),
    json_path: Path = Path("outputs/results/audited_train_1000_onecall/audited_records.json"),
    parquet_path: Path = Path("data/processed/audited_train_1000_onecall_labels.parquet"),
    limit: int | None = None,
    delay_seconds: float = 4.0,
    models: list[str] | None = None,
) -> None:
    print(f"Loading candidate sample: {sample_parquet}...")
    sample_df = pd.read_parquet(sample_parquet)
    sample_df["issue_id"] = sample_df["issue_id"].astype(str)

    existing_records: list[dict[str, Any]] = []
    if json_path.exists():
        existing_records = json.loads(json_path.read_text(encoding="utf-8"))
        print(f"Loaded {len(existing_records)} existing audited records from {json_path}")

    existing_keys = set((r["source"], r["project"], str(r["issue_id"])) for r in existing_records)
    to_audit = sample_df[
        ~sample_df.apply(lambda row: (row["source"], row["project"], str(row["issue_id"])) in existing_keys, axis=1)
    ].copy()

    print(f"Remaining un-audited records: {len(to_audit)} / {len(sample_df)}")
    if limit is not None and limit > 0:
        to_audit = to_audit.iloc[:limit]
        print(f"Limiting this run to {len(to_audit)} records.")

    if to_audit.empty:
        print("All records already audited!")
        return

    agents = []
    groq_models = models or ["openai/gpt-oss-120b", "openai/gpt-oss-20b", "qwen/qwen3.8-27b"]
    if os.getenv("GROQ_API_KEY"):
        for m in groq_models:
            agents.append(FourPerspectiveAgent(model=m, provider="groq", api_key_env="GROQ_API_KEY"))
    if os.getenv("GROQ_API_KEY_2"):
        for m in groq_models:
            agents.append(FourPerspectiveAgent(model=m, provider="groq", api_key_env="GROQ_API_KEY_2"))
    if os.getenv("OPENROUTER_API_KEY"):
        agents.append(FourPerspectiveAgent(model="openrouter/free", provider="openrouter"))

    active_names = [f"{a.provider}:{'k2' if '2' in getattr(a, 'api_key_env', '') else 'k1'}:{a.model.split('/')[-1]}" for a in agents]
    print(f"Active agent pool: {active_names} with {delay_seconds}s pacing between calls")

    audited_count = len(existing_records)
    new_records = list(existing_records)

    for idx, (_, row) in enumerate(to_audit.iterrows()):
        issue = row.to_dict()
        record = None
        attempt = 0
        while record is None:
            agent = agents[(idx + attempt) % len(agents)]
            attempt += 1
            try:
                record = await agent.evaluate_issue(issue)
            except Exception as e:
                err_str = str(e)
                wait_time = 5.0
                m_match = re.search(r"try again in (?:(\d+)m)?(\d+(?:\.\d+)?)s", err_str)
                if m_match:
                    mins = float(m_match.group(1) or 0)
                    secs = float(m_match.group(2) or 0)
                    wait_time = mins * 60 + secs + 2.0
                if attempt % len(agents) == 0:
                    print(f"[Wait all pool] All models busy, waiting {wait_time:.1f}s before retrying {row['project']} {row['issue_id']}...", flush=True)
                    await asyncio.sleep(min(wait_time, 60.0))
                else:
                    print(f"[Switch model] {agent.model.split('/')[-1]} busy, trying next model in pool...", flush=True)
                    await asyncio.sleep(1.5)

        new_records.append(record.model_dump())
        audited_count += 1
        flip_tag = " [FLIPPED]" if record.label_flipped else ""
        print(f"[{audited_count}/{len(sample_df)}] ({record.audit_model.split('/')[-1]}) {record.project} {record.issue_id}: {record.original_label} -> {record.judge_label}{flip_tag}", flush=True)

        # Checkpoint every 5 records
        if len(new_records) % 5 == 0:
            save_checkpoint(new_records, json_path, parquet_path)

        await asyncio.sleep(delay_seconds)

    save_checkpoint(new_records, json_path, parquet_path)
    print(f"Audit run completed! Total audited records: {len(new_records)}")
    if len(new_records) >= len(sample_df):
        print("\nAll 1,000 records audited! Auto-building treatment training dataset...")
        from src.treatment.build_treatment_dataset import build_treatment_dataset
        summary = build_treatment_dataset(overwrite=True)
        print("Treatment training dataset build completed successfully!")
        print(f"Summary: {summary}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Audit remaining records to reach 1,000")
    parser.add_argument("--limit", type=int, default=None, help="Max records to audit in this run")
    parser.add_argument("--delay", type=float, default=4.0, help="Delay between calls in seconds")
    parser.add_argument("--models", nargs="+", default=["openai/gpt-oss-120b", "openai/gpt-oss-20b", "qwen/qwen3.8-27b"], help="Model names on Groq to rotate")
    args = parser.parse_args()

    asyncio.run(run_audit(limit=args.limit, delay_seconds=args.delay, models=args.models))
